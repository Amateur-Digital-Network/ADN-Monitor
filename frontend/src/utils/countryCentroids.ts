/** Approximate country centroid for a DMR ID (first three digits), or null. */
export function centroidForDmrId(id: string | number): CountryCentroid | null {
  const digits = String(id ?? '').replace(/\D/g, '');
  if (digits.length < 3) return null;
  return COUNTRY_CENTROIDS[digits.slice(0, 3)] ?? null;
}
